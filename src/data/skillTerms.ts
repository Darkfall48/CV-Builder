/**
 * The vocabulary a job ad is read with. The portfolio this app grew out of
 * scored an offer against one person's tagged inventory; here nobody has
 * tagged anything, so the reading runs the other way: this dictionary finds
 * what the ad asks for, and the CV is then searched for each of those terms.
 *
 * It does not need to be exhaustive. A term earns its place when an ad names
 * it and a reader would expect the CV to answer it.
 */
